#!/usr/bin/env node
/**
 * gen-theme-token-names.mjs — generate the THEME TOKEN CONTRACT (ADR 0029).
 *
 * Theming is open: a consumer authors a `[data-theme="…"]` block and registers
 * it. "Every theme overrides every token" (@.claude/rules/theming.md) is the one
 * rule that makes that safe — a theme missing a token silently falls back to
 * `:root` and usually renders wrong. `pnpm theme-parity:check` enforces it for
 * the themes in THIS repo; a consumer's theme lives in THEIR repo, where our
 * gate cannot reach.
 *
 * So the contract is EXPORTED as data. This script derives it from
 * `src/themes.css` (the same union `check-theme-parity.mjs` holds every block
 * to) and writes `src/theme-token-names.generated.ts`, which the package
 * re-exports as `THEME_TOKEN_NAMES`. A consumer asserts their own stylesheet
 * covers it in their own test — no CSS parsing, no copy of our list to go stale.
 *
 * Usage:
 *   node scripts/gen-theme-token-names.mjs          # write
 *   node scripts/gen-theme-token-names.mjs --check  # verify freshness, exit 1 if stale
 *
 * Dependency-free, ESM, cwd-independent.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

import { TOKENS_PKG, readThemesCss, themeTokenContract } from "./lib/themes-io.mjs";

const OUT = join(TOKENS_PKG, "src", "theme-token-names.generated.ts");

/** Render the generated module for a contract list. Pure — the self-test uses it. */
export function renderModule(contract) {
  return `/**
 * GENERATED by \`packages/tokens/scripts/gen-theme-token-names.mjs\` — do not edit.
 * Run \`pnpm --filter @elabs-ai/components-tokens tokens:names\` to regenerate;
 * \`pnpm token-contract:check\` fails CI when this file is stale.
 *
 * The semantic tokens every theme must define (ADR 0029). Derived from the
 * active \`[data-theme="…"]\` blocks in \`src/themes.css\`, machinery excluded —
 * i.e. the exact set \`pnpm theme-parity:check\` holds the shipped themes to.
 */
export const THEME_TOKEN_NAMES = [
${contract.map((t) => `  "${t}",`).join("\n")}
] as const;

/** One of the ${contract.length} semantic tokens a complete theme defines. */
export type ThemeTokenName = (typeof THEME_TOKEN_NAMES)[number];
`;
}

/**
 * Anti-vacuity guard. An empty contract is the dangerous outcome, not a benign
 * one: every consumer's "my theme covers THEME_TOKEN_NAMES" assertion would pass
 * against it. Throws rather than exits so the self-test can assert it.
 */
export function assertNonEmptyContract(contract) {
  if (contract.length === 0) {
    throw new Error(
      "token-contract: derived ZERO tokens from themes.css — the block extraction " +
        "matched nothing (a renamed theme, a reformatted block). Refusing to write an " +
        "empty contract, which would pass every consumer's coverage assertion vacuously.",
    );
  }
  return contract;
}

function main() {
  let contract;
  try {
    contract = assertNonEmptyContract(themeTokenContract(readThemesCss()));
  } catch (err) {
    console.error(`✖ ${err.message}`);
    process.exit(1);
  }
  const next = renderModule(contract);
  const check = process.argv.includes("--check");
  let current = null;
  try {
    current = readFileSync(OUT, "utf8");
  } catch {
    /* not generated yet */
  }
  if (current === next) {
    console.log(`✔ token-contract: ${contract.length} tokens, generated file is fresh.`);
    return;
  }
  if (check) {
    console.error(
      `✖ token-contract: src/theme-token-names.generated.ts is STALE (${contract.length} tokens in themes.css).\n` +
        "  Fix: pnpm --filter @elabs-ai/components-tokens tokens:names",
    );
    process.exit(1);
  }
  writeFileSync(OUT, next);
  console.log(`✔ token-contract: wrote ${contract.length} tokens to ${OUT}`);
}

// Only when RUN, never when imported — the self-test imports `renderModule` and
// must not trigger a write or a `process.exit`.
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
