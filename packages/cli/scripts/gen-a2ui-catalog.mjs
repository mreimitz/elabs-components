#!/usr/bin/env node
/**
 * gen-a2ui-catalog.mjs (D2 — the generative-UI path) — the three derived artifacts of
 * the A2UI catalog, emitted from TWO sources that must agree:
 *
 *   packages/ai/src/a2ui/catalog.source.json   (hand-authored: WHICH components an agent
 *                                               may name, children, events, prop overrides)
 *   brand-ui.manifest.json                     (generated: the real prop tables + cva
 *                                               variants of those components)
 *
 * Outputs:
 *   packages/ai/src/a2ui/core/catalog.generated.ts
 *       `A2UI_CATALOG_SCHEMA` — per type: props (manifest props ∪ cva axes ∪ source
 *       overrides), events, children, summary (source, else the manifest's intent purpose).
 *       Imported by the validator AND the React renderer, so a prop the agent may emit
 *       is exactly a prop the component has.
 *   packages/cli/lib/a2ui.generated.mjs
 *       esbuild bundle of the engine-free core (validate, schema, completeJson, catalog)
 *       so the dependency-free CLI's `brand-ui a2ui` verbs run the SAME code as
 *       `@elabs-ai/components-ai` (the same shape RM-086 set for a generated schema).
 *   packages/ai/schemas/a2ui-surface.v1.schema.json
 *       the JSON Schema (draft 2020-12), published as `@elabs-ai/components-ai/a2ui/schema.json`.
 *
 *   node packages/cli/scripts/gen-a2ui-catalog.mjs          write all three
 *   node packages/cli/scripts/gen-a2ui-catalog.mjs --check  exit 1 if any is stale
 *
 * Runs AFTER the `manifest` step of `pnpm gen` (it reads the manifest). Prettier-formatted
 * so a rerun on unchanged sources is byte-identical.
 */
