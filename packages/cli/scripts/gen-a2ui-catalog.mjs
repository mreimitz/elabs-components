async function format(content, file) {
  const config = (await prettier.resolveConfig(join(REPO_ROOT, file))) ?? {};
  return prettier.format(content, { ...config, filepath: join(REPO_ROOT, file) });
}

/**
 * A handful of named type aliases seen ONLY as a bare identifier inside `Responsive<…>`
 * (the manifest's type string is the source's literal spelling — `Responsive<ChartPlotHeight>`,
 * never the inlined union — so there is nothing to pattern-match without knowing the alias).
 * Not a hand list of DEPRECATED props (§ below) — a closed, ADR-documented set of shapes
 * (`charts/responsive.ts`). An alias not listed here still gets a real Responsive wrapper;
 * only its own value shape falls back to `any`, exactly like an unresolved type does today.
 */
const NAMED_TYPE_SCHEMAS = {
  // `number | { aspect: number }` (`responsive.ts`) — both forms are shallow-checked, like
  // every other object-shaped prop in this catalog (`spec.ts`: "the runtime validator, not
  // the type, decides").
  ChartPlotHeight: { type: "number", oneOf: [{ type: "number" }, { type: "object" }] },
};

/** `Responsive<T>` (ADR 0039) → `T`, or the per-breakpoint `{ base, medium?, narrow? }` —
 *  a real `oneOf`, never collapsed to `any`. */
function responsiveSchema(inner) {
  return {
    type: inner.type,
    oneOf: [
      inner,
      {
        type: "object",
        description:
          "Per breakpoint: { base, medium?, narrow? } — base's shape is the value above.",
      },
    ],
  };
}

/** Manifest prop TYPE string → catalog prop schema, or null when an agent cannot set it. */
export function propSchemaFromType(type) {
  const t = String(type).trim();
  if (!t || t.includes("=>") || /^\(/.test(t)) return null; // functions
  const responsive = /^Responsive<([\s\S]+)>$/.exec(t);
  if (responsive) {
    const innerType = responsive[1].trim();
    const inner = NAMED_TYPE_SCHEMAS[innerType] ?? propSchemaFromType(innerType) ?? { type: "any" };
    return responsiveSchema(inner);
  }
  if (NAMED_TYPE_SCHEMAS[t]) return { ...NAMED_TYPE_SCHEMAS[t] };
  const parts = t.split("|").map((s) => s.trim());
  if (parts.length > 1 && parts.every((p) => /^"[^"]*"$/.test(p)))
    return { type: "string", enum: parts.map((p) => p.slice(1, -1)) };
  if (parts.length > 1 && parts.every((p) => /^-?\d+(\.\d+)?$/.test(p)))
    return { type: "number", enum: parts.map(Number) };
  if (t === "string") return { type: "string" };
  if (t === "number") return { type: "number" };
  if (t === "boolean") return { type: "boolean" };
  if (/^(React\.)?ReactNode$/.test(t)) return { type: "node" };
  if (/\[\]$/.test(t) || /^Array</.test(t)) return { type: "array" };
  if (/^\{/.test(t)) return { type: "object" };
  return { type: "any" };
}

/**
 * A prop's deprecation, from data — never a hand list of names. The manifest's own
 * `deprecated` field (joined from the ADR 0042 definitions snapshot's alias rows,
 * `core.mjs#joinDefinitions`) wins when present; otherwise the `@deprecated` JSDoc tag
 * every deprecation carries by policy (`DEPRECATION.md` §1) is read straight off the
 * description text — covers a prop outside the snapshot (no chart/part/surface
 * definition), e.g. `AutoChart.height`.
 */
const DEPRECATED_TAG = /@deprecated\b\s*(.*)/is;
export function deprecationFromProp(prop) {
  if (prop?.deprecated && typeof prop.deprecated === "object") {
    return { replacement: prop.deprecated.replacement };
  }
  const m = DEPRECATED_TAG.exec(String(prop?.description || ""));
  if (!m) return null;
  return { replacement: /`([^`]+)`/.exec(m[1])?.[1] };
}

/**
 * The agent-facing description: the manifest's own text (first line, ≤160 chars), same as
 * before. For a deprecated prop the `@deprecated …` note — naming the replacement — is
 * NEVER lost to truncation: it is split off first and the summary is shortened around it,
 * so a long description cannot push the replacement name past the 160-char budget. The raw
 * `@deprecated` JSDoc tag word itself is never echoed into agent-facing prose — only what
 * follows it (or, lacking that, the replacement name alone).
 */
export function propDescription(rawDescription, deprecated) {
  const desc = String(rawDescription || "")
    .split(/\n/)[0]
    .replace(/\s+/g, " ")
    .trim();
  if (!deprecated) return desc.length > 160 ? `${desc.slice(0, 157)}…` : desc;
  const idx = desc.search(/@deprecated\b/i);
  const tagText =
    idx === -1
      ? ""
      : desc
          .slice(idx)
          .replace(/^@deprecated\b\s*/i, "")
          .trim();
  let note = tagText
    ? `Deprecated — ${tagText.charAt(0).toLowerCase()}${tagText.slice(1)}`
    : deprecated.replacement
      ? `Deprecated — use \`${deprecated.replacement}\`.`
      : "Deprecated.";
  if (note.length > 160) note = `${note.slice(0, 157)}…`;
  const summary = (idx === -1 ? desc : desc.slice(0, idx)).trim();
  if (!summary) return note;
  const budget = Math.max(0, 160 - note.length - 1);
  const head = summary.length > budget ? `${summary.slice(0, Math.max(0, budget - 1))}…` : summary;
  return `${head} ${note}`;
}

/** Props an agent must never drive even when the component declares them. */
const NEVER =
  /^(on[A-Z]|render|as$|asChild$|children$|className$|style$|ref$|key$|dangerouslySetInnerHTML$)/;

/** The cva axes a `VariantProps<typeof xVariants>` (possibly inside `Omit<…, "a" | "b">`) contributes. */
export function variantAxes(extendsList, variants) {
  const out = {};
  for (const ext of extendsList || []) {
    const m = /VariantProps<typeof (\w+)>/.exec(ext);
    if (!m) continue;
    const omitted = new Set(
      [...(/Omit<[^,]+,\s*(.+)>\s*$/.exec(ext)?.[1] ?? "").matchAll(/"([^"]+)"/g)].map((x) => x[1]),
    );
    const v = Object.values(variants || {}).find((x) => x.source === m[1]);
    if (!v) continue;
    for (const [axis, values] of Object.entries(v.variants || {})) {
      if (omitted.has(axis)) continue;
      const enumValues = values.map((x) => (/^-?\d+$/.test(x) ? Number(x) : x));
      out[axis] = {
        type: typeof enumValues[0] === "number" ? "number" : "string",
        enum: enumValues,
        ...(v.defaultVariants?.[axis] !== undefined ? { default: v.defaultVariants[axis] } : {}),
      };
    }
  }
  return out;
}

const sortKeys = (o) =>
  Object.fromEntries(Object.entries(o).sort(([a], [b]) => a.localeCompare(b)));

/**
 * Coverage check (F03, RM-197): every `@elabs-ai/components-charts` catalog entry needs
 * agent-facing prose — a `summary`, from `catalog.source.json` or, failing that, the
 * manifest's own intent purpose (`buildCatalog` above). Runs on every `pnpm gen`/
 * `pnpm gen --check`, so a chart type added to the catalog with no prose fails the build
 * instead of shipping silently thin. Deliberately in the gen script, not a `pnpm check`
 * rule — the maintainer wants no new gates for this track.
 */
export function assertProseCoverage(source, catalog) {
  const missing = Object.entries(source.types)
    .filter(([, src]) => src.package === CHARTS && !src.builtin)
    .map(([type]) => type)
    .filter((type) => !catalog[type]?.summary?.trim());
  if (missing.length) {
    throw new Error(
      `gen-a2ui-catalog: missing prose for ${missing.join(", ")} — add a "summary" in catalog.source.json (or a manifest intent purpose).`,
    );
  }
}

/** Build the catalog schema object from the two sources. Throws on a type the manifest lacks. */
export function buildCatalog(source, manifest) {
  const catalog = {};
  for (const [type, src] of Object.entries(source.types)) {
    const pkgName = src.package || UI;
    const pkg = manifest.packages?.[pkgName];
    if (!pkg) throw new Error(`manifest has no ${pkgName} package — run \`pnpm gen\` first`);
    const exported = new Set((pkg.components || []).map((c) => c.name));
    const entry = {
      ...(src.builtin ? { builtin: true } : {}),
      children: Boolean(src.children),
      props: {},
      events: src.events || {},
      source: src.builtin ? "builtin" : pkgName,
    };
    if (!src.builtin) {
      if (!exported.has(type))
        throw new Error(`catalog.source.json names "${type}", which ${pkgName} does not export`);
      const ui = pkg;
      const table = ui.props?.[type];
      const props = {};
      const omit = new Set(src.omit || []);
      for (const p of table?.props || []) {
        if (NEVER.test(p.name) || omit.has(p.name)) continue;
        const schema = propSchemaFromType(p.type);
        // A prop whose type the manifest cannot name (`any`) is unknowable to an agent
        // too — it enters the catalog only through an explicit source override. A prop
        // wrapped in `Responsive<…>` is never bare `any`, though: it always carries a
        // real `oneOf` (the wrapper), even when its own value type could not be named.
        if (!schema || (schema.type === "any" && !schema.oneOf && !src.props?.[p.name])) continue;
        if (!p.optional) schema.required = true;
        // Deprecated names STAY (never dropped) until 6.0.0, flagged and still valid
        // (ADR 0042 §8) — never a hand list of names, always read off the data.
        const deprecated = deprecationFromProp(p);
        const desc = propDescription(p.description, deprecated);
        if (desc) schema.description = desc;
        if (deprecated) schema.deprecated = true;
        props[p.name] = schema;
      }
      Object.assign(props, variantAxes(table?.extends, ui.variants));
      entry.props = props;
      const purpose = ui.intent?.[type]?.purpose;
      if (purpose) entry.summary = purpose;
    }
    // Source overrides win per prop (they are the curated, agent-facing truth).
    for (const [name, override] of Object.entries(src.props || {})) {
      const base = entry.props[name] || {};
      entry.props[name] = {
        ...base,
        ...override,
        type: override.type || (override.enum ? typeof override.enum[0] : base.type) || "any",
      };
    }
    if (src.summary) entry.summary = src.summary;
    entry.props = sortKeys(entry.props);
    catalog[type] = entry;
  }
  assertProseCoverage(source, catalog);
  return sortKeys(catalog);
}

/** Split a built catalog by where it renders: the ai package (ui + builtins), charts, data. */
export function splitCatalog(catalog) {
  const ai = {};
  const charts = {};
  const data = {};
  for (const [type, entry] of Object.entries(catalog)) {
    (entry.source === CHARTS ? charts : entry.source === DATA ? data : ai)[type] = entry;
  }
  return { ai, charts, data };
}

/** All artifacts as `{ path: content }`, computed without touching the tree. */
export async function renderA2uiArtifacts() {
  const source = JSON.parse(readFileSync(join(REPO_ROOT, SOURCE_PATH), "utf8"));
  const manifest = JSON.parse(readFileSync(join(REPO_ROOT, "brand-ui.manifest.json"), "utf8"));
  const { ai: catalog, charts, data } = splitCatalog(buildCatalog(source, manifest));

  const ts = await format(
    `${TS_HEADER}export const A2UI_CATALOG_VERSION = ${JSON.stringify(source.version)};\n\n` +
      `export const A2UI_CATALOG_SCHEMA: A2uiCatalogSchema = ${JSON.stringify(catalog, null, 2)};\n`,
    CATALOG_TS_PATH,
  );
  const chartsTs = await format(
    `${CHARTS_TS_HEADER}export const CHARTS_A2UI_CATALOG_SCHEMA: ChartsA2uiCatalogSchema = ${JSON.stringify(charts, null, 2)};\n`,
    CHARTS_CATALOG_TS_PATH,
  );

  const dataTs = await format(
    `${DATA_TS_HEADER}export const DATA_A2UI_CATALOG_SCHEMA: DataA2uiCatalogSchema = ${JSON.stringify(data, null, 2)};\n`,
    DATA_CATALOG_TS_PATH,
  );

  // Bundle against the FRESH catalog: esbuild reads catalog.generated.ts from disk, so
  // hand it the rendered text through a plugin instead of the (possibly stale) file.
  const result = await build({
    stdin: { contents: ENTRY, resolveDir: CORE_DIR, loader: "ts", sourcefile: "entry.ts" },
    absWorkingDir: REPO_ROOT,
    bundle: true,
    format: "esm",
    platform: "neutral",
    target: "es2022",
    charset: "ascii",
    legalComments: "none",
    write: false,
    logLevel: "silent",
    plugins: [
      {
        name: "fresh-catalog",
        setup(b) {
          // A repo-relative virtual path: esbuild prints it in a comment inside the
          // bundle, and a machine-specific absolute path must never be committed.
          b.onResolve({ filter: /catalog\.generated$/ }, () => ({
            path: "packages/ai/src/a2ui/core/catalog.generated.ts",
            namespace: "fresh",
          }));
          b.onLoad({ filter: /.*/, namespace: "fresh" }, () => ({
            contents: ts,
            loader: "ts",
            resolveDir: CORE_DIR,
          }));
          // The charts half, as a virtual module (its `import type` line is erased by esbuild).
          b.onResolve({ filter: /^a2ui-charts-catalog$/ }, () => ({
            path: "packages/charts/src/a2ui/catalog.generated.ts",
            namespace: "fresh-charts",
          }));
          b.onLoad({ filter: /.*/, namespace: "fresh-charts" }, () => ({
            contents: chartsTs.replace(/^import type [^\n]*\n/m, ""),
            loader: "ts",
            resolveDir: CORE_DIR,
          }));
          // The data half, likewise.
          b.onResolve({ filter: /^a2ui-data-catalog$/ }, () => ({
            path: "packages/data/src/a2ui/catalog.generated.ts",
            namespace: "fresh-data",
          }));
          b.onLoad({ filter: /.*/, namespace: "fresh-data" }, () => ({
            contents: dataTs.replace(/^import type [^\n]*\n/m, ""),
            loader: "ts",
            resolveDir: CORE_DIR,
          }));
        },
      },
    ],
  });
  const bundleText = result.outputFiles[0].text;
  const bundle = await format(BUNDLE_HEADER + bundleText, BUNDLE_PATH);

  const mod = await import(
    `data:text/javascript;base64,${Buffer.from(bundleText).toString("base64")}`
  );
  // The published schema covers EVERY shipped catalog (ui + charts): an agent reads one
  // contract; the app binds the catalogs it installs and unknown types fail at render.
  const schema = await format(
    `${JSON.stringify(
      mod.buildA2uiSurfaceSchema({
        ...mod.A2UI_CATALOG_SCHEMA,
        ...mod.CHARTS_A2UI_CATALOG_SCHEMA,
        ...mod.DATA_A2UI_CATALOG_SCHEMA,
      }),
      null,
      2,
    )}\n`,
    SCHEMA_PATH,
  );
  return {
    [CATALOG_TS_PATH]: ts,
    [CHARTS_CATALOG_TS_PATH]: chartsTs,
    [DATA_CATALOG_TS_PATH]: dataTs,
    [BUNDLE_PATH]: bundle,
    [SCHEMA_PATH]: schema,
  };
}

export async function main(argv = process.argv.slice(2)) {
  const check = argv.includes("--check");
  const artifacts = await renderA2uiArtifacts();
  const stale = [];
  for (const [file, content] of Object.entries(artifacts)) {
    const abs = join(REPO_ROOT, file);
    const current = existsSync(abs) ? readFileSync(abs, "utf8") : null;
    if (current === content) continue;
    if (check) {
      stale.push(file);
      continue;
    }
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, content);
    console.log(`gen-a2ui-catalog: wrote ${file}`);
  }
  if (stale.length) {
    console.error(`gen-a2ui-catalog: stale — ${stale.join(", ")}. Run \`pnpm gen\`.`);
    process.exitCode = 1;
  }
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) await main();
