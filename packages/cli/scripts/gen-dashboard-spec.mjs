#!/usr/bin/env node
/**
 * gen-dashboard-spec.mjs (RM-086, #427) — the two derived artifacts of the dashboard
 * spec core, emitted from ONE source (`packages/charts/src/dashboard/core`):
 *
 *   packages/cli/lib/dashboard-spec.generated.mjs
 *       esbuild bundle of `autoLayout`, `validateDashboardSpec`, `DASHBOARD_SPEC_SCHEMA`
 *       and `BUILT_IN_TILE_KIND_DEFAULTS`. The CLI is dependency-free plain `.mjs` and
 *       publishes standalone, so `brand-ui dashboard-spec` runs this bundle instead of
 *       importing `@elabs-ai/components-charts` (which is TypeScript source + React).
 *   packages/charts/schemas/dashboard-spec.v1.schema.json
 *       the JSON Schema document (`$id` = DASHBOARD_SPEC_SCHEMA_ID), for editors and
 *       JSON-Schema tooling; published via the charts `./dashboard/schema.json` export.
 *
 *   node packages/cli/scripts/gen-dashboard-spec.mjs          write both
 *   node packages/cli/scripts/gen-dashboard-spec.mjs --check  exit 1 if either is stale
 *
 * Both outputs are Prettier-formatted with the repo config, so a rerun on unchanged
 * source is byte-identical (registered as the `dashboard-spec` step of `pnpm gen`).
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { build } from "esbuild";
import prettier from "prettier";

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "..");
const CORE_DIR = join(REPO_ROOT, "packages/charts/src/dashboard/core");

export const BUNDLE_PATH = "packages/cli/lib/dashboard-spec.generated.mjs";
export const SCHEMA_PATH = "packages/charts/schemas/dashboard-spec.v1.schema.json";

const ENTRY = [
  'export { autoLayout } from "./auto-layout";',
  'export { validateDashboardSpec } from "./validate";',
  'export { BUILT_IN_TILE_KIND_DEFAULTS, DASHBOARD_SPEC_SCHEMA, DASHBOARD_SPEC_SCHEMA_ID } from "./schema";',
  "",
].join("\n");

const HEADER = `// GENERATED by packages/cli/scripts/gen-dashboard-spec.mjs from
// packages/charts/src/dashboard/core (RM-086) — do not edit; run \`pnpm gen\`.
/* eslint-disable */
`;

async function format(content, file) {
  const config = (await prettier.resolveConfig(join(REPO_ROOT, file))) ?? {};
  return prettier.format(content, { ...config, filepath: join(REPO_ROOT, file) });
}

/** Both artifacts as `{ path: content }`, computed without touching the tree. */
export async function renderDashboardSpecArtifacts() {
  const result = await build({
    stdin: { contents: ENTRY, resolveDir: CORE_DIR, loader: "ts", sourcefile: "entry.ts" },
    absWorkingDir: REPO_ROOT,
    bundle: true,
    format: "esm",
    platform: "neutral",
    target: "es2022",
    charset: "ascii",
    legalComments: "none",
    write: false,
    logLevel: "silent",
  });
  const bundle = await format(HEADER + result.outputFiles[0].text, BUNDLE_PATH);

  // Import the bundle we just built (from a data URL — no temp file) so the schema
  // JSON is exactly the object the CLI will print.
  const mod = await import(
    `data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString("base64")}`
  );
  const schema = await format(
    `${JSON.stringify(mod.DASHBOARD_SPEC_SCHEMA, null, 2)}\n`,
    SCHEMA_PATH,
  );
  return { [BUNDLE_PATH]: bundle, [SCHEMA_PATH]: schema };
}

export async function main(argv = process.argv.slice(2)) {
  const check = argv.includes("--check");
  const artifacts = await renderDashboardSpecArtifacts();
  const stale = [];
  for (const [file, content] of Object.entries(artifacts)) {
    const abs = join(REPO_ROOT, file);
    const current = existsSync(abs) ? readFileSync(abs, "utf8") : null;
    if (current === content) continue;
    if (check) {
      stale.push(file);
      continue;
    }
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, content);
    console.log(`gen-dashboard-spec: wrote ${file}`);
  }
  if (stale.length) {
    console.error(`gen-dashboard-spec: stale — ${stale.join(", ")}. Run \`pnpm gen\`.`);
    process.exitCode = 1;
  }
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) await main();
