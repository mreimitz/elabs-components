/**
 * a11y-baseline-reporter.mjs — a Vitest reporter that harvests the axe result of
 * every story run, so the #316 ratchet baseline is GENERATED, never hand-kept.
 *
 * `@storybook/addon-vitest` stamps each test task with `meta.storyId` and
 * `meta.reports` (see its `vitest-plugin/test-utils.js`: `_task.meta.reports =
 * composedStory.reporting.reports`). `@storybook/addon-a11y` pushes an
 * `{ type: "a11y", result }` report there for EVERY story — including the ones
 * this repo exempts (`parameters.a11y.test: "todo"`), because the addon still
 * runs axe and only downgrades the report's status. That is what makes a
 * ratchet possible: an exempted story's violations stay visible, so the gate can
 * see when one has been cleaned up and the exemption can be dropped.
 *
 * Wire it with `pnpm a11y:baseline:run`; it writes `scripts/.a11y-run.json`
 * (git-ignored — a measurement, not a source of truth).
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
export const RUN_PATH = join(SCRIPT_DIR, ".a11y-run.json");

/**
 * Rule ids out of an addon-a11y matcher message. The FALLBACK path, and it is
 * load-bearing: `meta.reports` is stamped only after `composedStory.run()`
 * RESOLVES, so a story that axe actually failed (error mode) reports nothing.
 * Its message ends each violation line with the rule id in parentheses —
 * `"Elements must meet minimum color contrast ratio thresholds (color-contrast)"`.
 */
export function readErrorRules(errors) {
  const rules = new Set();
  for (const error of Array.isArray(errors) ? errors : []) {
    const message = typeof error?.message === "string" ? error.message : "";
    for (const [, id] of message.matchAll(/\(([a-z][a-z0-9]*(?:-[a-z0-9]+)+)\)/g)) rules.add(id);
  }
  return [...rules].sort();
}

/** Pull `{ storyId, rules }` out of one task, or null if it isn't a story. */
export function readTaskMeta(meta, errors) {
  const storyId = meta?.storyId;
  if (typeof storyId !== "string" || storyId.length === 0) return null;
  const reports = Array.isArray(meta.reports) ? meta.reports : [];
  const a11y = reports.find((r) => r?.type === "a11y");
  if (!a11y) return { storyId, rules: readErrorRules(errors) };
  const violations = Array.isArray(a11y.result?.violations) ? a11y.result.violations : [];
  const rules = [...new Set(violations.map((v) => v?.id).filter((id) => typeof id === "string"))];
  rules.sort();
  return { storyId, rules };
}

/** Serialize the harvested map into the on-disk run shape (sorted, stable). */
export function serializeRun(stories) {
  const sorted = [...stories.entries()].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  return `${JSON.stringify(
    {
      $comment:
        "Generated by `pnpm a11y:baseline:run`. A measurement of one Storybook test run, not a source of truth — git-ignored. `pnpm a11y:baseline:check --update` turns it into scripts/a11y-baseline.json.",
      generatedAt: new Date().toISOString(),
      stories: Object.fromEntries(sorted),
    },
    null,
    2,
  )}\n`;
}

export default class A11yBaselineReporter {
  #stories = new Map();

  #collect(meta, errors) {
    const entry = readTaskMeta(meta, errors);
    if (!entry) return;
    // Union across passes: axe can only see what a given render reached, so a
    // story that violates intermittently must not be un-recorded by a luckier
    // second look within the same run.
    const seen = this.#stories.get(entry.storyId) ?? [];
    this.#stories.set(entry.storyId, [...new Set([...seen, ...entry.rules])].sort());
  }

  #walk(tasks) {
    for (const task of tasks ?? []) {
      if (Array.isArray(task?.tasks)) this.#walk(task.tasks);
      else this.#collect(task?.meta, task?.result?.errors);
    }
  }

  #write() {
    writeFileSync(RUN_PATH, serializeRun(this.#stories), "utf8");
  }

  // Vitest 3's per-case hook — the reliable one under browser mode.
  onTestCaseResult(testCase) {
    try {
      const meta = typeof testCase?.meta === "function" ? testCase.meta() : testCase?.meta;
      const result = typeof testCase?.result === "function" ? testCase.result() : testCase?.result;
      this.#collect(meta, result?.errors);
    } catch {
      // A reporter must never fail the run; a missed case simply isn't baselined.
    }
  }

  // Legacy task-tree hook, kept as a belt-and-braces harvest + the write point.
  onFinished(files) {
    this.#walk(files);
    this.#write();
  }

  // Vitest 3's replacement for `onFinished`; writing twice is idempotent.
  onTestRunEnd() {
    this.#write();
  }
}
