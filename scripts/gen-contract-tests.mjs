#!/usr/bin/env node
/**
 * gen-contract-tests.mjs — one contract test per exported component (S2).
 *
 * The problem this replaces: "does this component have a story" (grepped by
 * `check-components-registered.mjs` et al.) proves a story FILE exists, never
 * that the component actually forwards a ref, merges a caller `className`,
 * carries its `data-slot`, or is usable at phone/tablet/desktop widths in both
 * themes. This generator turns `.claude/rules/component-api.md` +
 * `.claude/rules/accessibility.md` + `.claude/rules/styling-and-tokens.md`
 * into EXECUTABLE per-component probes, derived from the manifest + each
 * component's own `Default` story — never hand-written per component.
 *
 * ## Discovery
 *
 * For every `brand-ui.manifest.json` `kind: "value"` PascalCase export, find
 * the story file whose meta `component:` field names it exactly AND that
 * exports `Default` with plain `args` (no custom `render:` — we cannot safely
 * inject a probe ref/className into arbitrary caller-composed JSX). The
 * co-located `<module>.stories.tsx` is tried first; failing that, any
 * `*.stories.tsx` in the same package that imports or renders the component
 * (mirrors `check-variant-coverage.mjs`'s `findStoryFilesFor`).
 *
 * A component that fails discovery is NOT a bug — most manifest exports are
 * compound SUB-PARTS (`CardHeader`, `DialogContent`, …) that share their
 * parent's one story file and were never meant to carry their own `Default`.
 * `discoverCoverage()` records why (`skipped[].reason`) so the generator's
 * own summary stays honest instead of silently under-covering.
 *
 * ## Output (two suites, one discovery pass)
 *
 * - **jsdom** — `packages/<pkg>/src/__contract__/<kebab>.contract.test.tsx`:
 *   forwardRef (skipped when the export isn't one), `className` merge, root
 *   `data-slot`. Runs under each package's existing jsdom `vitest.config.ts`.
 * - **browser** — `apps/docs/contract/<pkg>.contract.test.tsx`: axe (wcag2a +
 *   wcag2aa) and no-horizontal-overflow, swept over every
 *   `@elabs-ai/components-tokens` `BUILT_IN_THEMES` entry × `WIDTHS`. Runs
 *   under the `contract` vitest project (real Chromium via Playwright).
 *
 * ## Known failures (the ratchet)
 *
 * `scripts/check/contract-known-failures.json` maps
 * `"<storyId>|<theme>|<width>|<assertion>"` → a one-line reason. A generated
 * assertion whose key is listed renders as `it.fails(...)` — so FIXING the
 * underlying gap flips that test red (a regression, not a pass to celebrate)
 * until the key is removed, which is the ratchet's teeth. `theme`/`width` are
 * literally `"jsdom"` for the jsdom suite (it has neither axis). The
 * `contract-known-failures` runner rule (`scripts/check/rules/`) mirrors the
 * file's keys into the shared `scripts/check/baseline.json`, so growing the
 * known-failures list is a visible, reviewed ratchet move like every other
 * gate here — never a silent way to mute a new gap.
 *
 * Idempotent + deterministic: re-running with no source changes rewrites
 * byte-identical files. `--check` diffs instead of writing (CI-safe).
 *
 * Flags:
 *   --check              exit 1 if generated output would change; write nothing.
 *   --package <name>     only this package's folder name (e.g. "ui"); repeatable.
 *   --suite jsdom|browser|all   default "all".
 */
import { readFileSync, writeFileSync, existsSync, readdirSync, mkdirSync, rmSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join, relative, basename } from "node:path";

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
export const REPO_ROOT = dirname(SCRIPT_DIR);
const MANIFEST_PATH = join(REPO_ROOT, "brand-ui.manifest.json");
export const KNOWN_FAILURES_PATH = join(REPO_ROOT, "scripts/check/contract-known-failures.json");
const CONTRACT_DIR_NAME = "__contract__";
const BROWSER_CONTRACT_DIR = join(REPO_ROOT, "apps/docs/contract");

export const GENERATED_HEADER =
  "// GENERATED by scripts/gen-contract-tests.mjs — do not edit; re-run the generator instead.\n";

export const WIDTHS = [375, 768, 1280]; // phone / tablet / desktop

// ── naming ───────────────────────────────────────────────────────────────

/** SCREAMING_SNAKE_CASE constants and non-PascalCase exports are never components. */
const CONSTANT_NAME_RE = /^[A-Z0-9]+(?:_[A-Z0-9]+)*$/;
export function isComponentName(name) {
  return typeof name === "string" && /^[A-Z]/.test(name) && !CONSTANT_NAME_RE.test(name);
}

/** `AgentTimeline` -> `agent-timeline` — the `data-slot` convention (component-api.md). */
export function kebabSlot(name) {
  return name
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1-$2")
    .toLowerCase();
}

/** One Storybook `toId()` segment: lowercase, non-alnum runs collapse to one dash. */
function sbIdPart(s) {
  return s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

/** `"AI/ChangeReview"`, `"Default"` -> `"ai-changereview--default"` (storybook-mcp.md). */
export function storyIdOf(title, exportName) {
  return `${title.split("/").map(sbIdPart).join("-")}--${sbIdPart(exportName)}`;
}

// ── story-file scanning (dependency-free; mirrors check-variant-coverage.mjs) ──

function collectStoryFiles(dir, out = []) {
  let entries;
  try {
    entries = readdirSync(dir, { withFileTypes: true });
  } catch {
    return out;
  }
  for (const e of entries) {
    if (e.name === "node_modules") continue;
    const p = join(dir, e.name);
    if (e.isDirectory()) collectStoryFiles(p, out);
    else if (/\.stories\.tsx$/.test(e.name)) out.push(p);
  }
  return out.sort();
}

/**
 * Split a story file into per-export blocks (`export const Name ...` up to
 * the next such export), so a `Default` block's own body — not some other
 * export's — is what `hasCustomRender` inspects.
 */
export function findStoryBlocks(text) {
  const exportNameRe = /export\s+const\s+([A-Za-z_$][A-Za-z0-9_$]*)\s*[:=]/g;
  const matches = [...text.matchAll(exportNameRe)];
  const blocks = [];
  for (let i = 0; i < matches.length; i++) {
    const name = matches[i][1];
    if (name === "meta") continue;
    const start = matches[i].index;
    const end = i + 1 < matches.length ? matches[i + 1].index : text.length;
    blocks.push({ name, text: text.slice(start, end) });
  }
  return blocks;
}

/** The meta object lives before the first `export const` story. */
export function parseMetaHead(text) {
  const firstExport = text.search(/export\s+const\s+[A-Za-z_$]/);
  const head = firstExport === -1 ? text : text.slice(0, firstExport);
  const component = head.match(/\bcomponent:\s*([A-Za-z_$][\w$]*)/)?.[1] ?? null;
  const title = head.match(/\btitle:\s*["'`]([^"'`]+)["'`]/)?.[1] ?? null;
  return { component, title };
}

/** A `Default` block with its own `render:`/`render(` is opaque to a probe. */
export function hasCustomRender(blockText) {
  return /\brender\s*[:(]/.test(blockText);
}

/** Every story file under `pkgSrcDir` that imports or renders `componentName`. */
export function findStoryFilesFor(pkgSrcDir, componentName, allStoryFiles, readFile) {
  const importRe = new RegExp(`import\\s*\\{[^}]*\\b${componentName}\\b[^}]*\\}\\s*from`);
  const jsxRe = new RegExp(`<${componentName}[\\s/>]`);
  return allStoryFiles.filter((f) => {
    const text = readFile(f);
    return importRe.test(text) || jsxRe.test(text);
  });
}

/**
 * Resolve one component's contract-probe eligibility: the story file whose
 * meta names it exactly and whose `Default` export uses plain args.
 * @returns {{ file, title } | null} plus sets `reason` on the returned skip marker
 */
function resolveComponentStory(comp, pkgSrcDir, allStoryFiles, readFile, repoRoot) {
  const modulePath = join(repoRoot, comp.module);
  const coLocated = modulePath.replace(/\.tsx?$/, ".stories.tsx");
  const candidates = [];
  if (existsSync(coLocated)) candidates.push(coLocated);
  for (const f of findStoryFilesFor(pkgSrcDir, comp.name, allStoryFiles, readFile)) {
    if (!candidates.includes(f)) candidates.push(f);
  }

  let reason = "no story references this export";
  for (const file of candidates) {
    const text = readFile(file);
    const meta = parseMetaHead(text);
    if (meta.component !== comp.name) {
      reason = "sub-part or shared story file (meta.component names a different export)";
      continue;
    }
    const def = findStoryBlocks(text).find((b) => b.name === "Default");
    if (!def) {
      reason = "story file has no Default export";
      continue;
    }
    if (hasCustomRender(def.text)) {
      reason = "Default story uses a custom render (cannot inject a probe ref/className)";
      continue;
    }
    return { ok: { file, title: meta.title ?? comp.name } };
  }
  return { skip: reason };
}

// ── discovery ────────────────────────────────────────────────────────────

/**
 * @returns {{ covered: {pkgName, pkgDir, name, module, storyFile, title, storyId}[],
 *             skipped: {pkgName, name, module, reason}[] }}
 */
export function discoverCoverage(
  manifest,
  repoRoot = REPO_ROOT,
  readFile = (f) => readFileSync(f, "utf8"),
) {
  const covered = [];
  const skipped = [];
  for (const [pkgName, pkg] of Object.entries(manifest.packages ?? {})) {
    const pkgSrcDir = join(repoRoot, pkg.path, "src");
    const allStoryFiles = collectStoryFiles(pkgSrcDir);
    for (const comp of pkg.components ?? []) {
      if (comp.kind !== "value" || !isComponentName(comp.name)) continue;
      if (!/^packages\/[^/]+\/src\/.+\.tsx$/.test(comp.module)) continue;
      if (/\.(test|stories)\.tsx$/.test(comp.module)) continue;
      const result = resolveComponentStory(comp, pkgSrcDir, allStoryFiles, readFile, repoRoot);
      if (result.ok) {
        covered.push({
          pkgName,
          pkgDir: pkg.path,
          name: comp.name,
          module: comp.module,
          storyFile: relative(repoRoot, result.ok.file),
          title: result.ok.title,
          storyId: storyIdOf(result.ok.title, "Default"),
        });
      } else {
        skipped.push({ pkgName, name: comp.name, module: comp.module, reason: result.skip });
      }
    }
  }
  covered.sort((a, b) => `${a.pkgName}/${a.name}`.localeCompare(`${b.pkgName}/${b.name}`));
  skipped.sort((a, b) => `${a.pkgName}/${a.name}`.localeCompare(`${b.pkgName}/${b.name}`));
  return { covered, skipped };
}

// ── known failures ───────────────────────────────────────────────────────

export function loadKnownFailures(path = KNOWN_FAILURES_PATH) {
  if (!existsSync(path)) return {};
  return JSON.parse(readFileSync(path, "utf8"));
}

// ── jsdom suite ──────────────────────────────────────────────────────────

function posixRel(from, to) {
  const rel = relative(dirname(from), to)
    .replace(/\\/g, "/")
    .replace(/\.tsx?$/, "");
  return rel.startsWith(".") ? rel : `./${rel}`;
}

export function renderJsdomTest(entry, repoRoot = REPO_ROOT) {
  const outFile = join(
    repoRoot,
    entry.pkgDir,
    "src",
    CONTRACT_DIR_NAME,
    `${kebabSlot(entry.name)}.contract.test.tsx`,
  );
  const storyImport = posixRel(outFile, join(repoRoot, entry.storyFile));
  const knownFailuresImport = posixRel(outFile, KNOWN_FAILURES_PATH);
  const slot = kebabSlot(entry.name);

  const body = `${GENERATED_HEADER}/**
 * Contract probe for ${entry.name} (\`${entry.module}\`), derived from its
 * \`Default\` story (${entry.storyFile}). See scripts/gen-contract-tests.mjs.
 */
import { describe, it, expect, afterEach } from "vitest";
import { render, cleanup } from "@testing-library/react";
import { createRef } from "react";
import * as stories from "${storyImport}";
import knownFailuresJson from "${knownFailuresImport}";

afterEach(cleanup);

// Every component here has its own prop/ref/element shape; a generated probe
// stays generic on purpose (loosely typed, not untyped — see
// scripts/gen-contract-tests.mjs) rather than re-deriving each one.
const KNOWN_FAILURES: Record<string, string> = knownFailuresJson;
const meta = stories.default as { component?: unknown; args?: Record<string, unknown> };
const Default = (stories as { Default?: { args?: Record<string, unknown> } }).Default;
// eslint-disable-next-line @typescript-eslint/no-explicit-any -- probe target; see comment above
const Component = meta.component as any;
const args = { ...(meta.args ?? {}), ...(Default?.args ?? {}) };
const isForwardRefComponent = Component?.["$$typeof"] === Symbol.for("react.forward_ref");

/** Wrap a known, tracked failure in \`it.fails\` so fixing it forces the key's removal. */
function contractIt(assertion: string, name: string, fn: () => void) {
  const key = \`${entry.storyId}|jsdom|jsdom|\${assertion}\`;
  const reason = KNOWN_FAILURES[key];
  if (reason) return it.fails(\`\${name} (known failure: \${reason})\`, fn);
  return it(name, fn);
}

describe("${entry.name} contract", () => {
  it.skipIf(!isForwardRefComponent)("forwards a ref to a DOM element", () => {
    const ref = createRef<Element>();
    render(<Component {...args} ref={ref} />);
    expect(ref.current).toBeInstanceOf(Element);
  });

  contractIt("className", "merges a caller className onto the root", () => {
    const { container } = render(<Component {...args} className="contract-probe" />);
    expect(container.querySelector(".contract-probe")).not.toBeNull();
  });

  contractIt("data-slot", 'exposes data-slot="${slot}" on its root', () => {
    const { container } = render(<Component {...args} />);
    expect(container.querySelector('[data-slot="${slot}"]')).not.toBeNull();
  });
});
`;
  return { outFile, body };
}

// ── browser suite ────────────────────────────────────────────────────────

export function renderBrowserTest(pkgShortName, entries, repoRoot = REPO_ROOT) {
  const outFile = join(BROWSER_CONTRACT_DIR, `${pkgShortName}.contract.test.tsx`);
  const knownFailuresImport = posixRel(outFile, KNOWN_FAILURES_PATH);

  const blocks = entries
    .map((entry) => {
      const storyImport = posixRel(outFile, join(repoRoot, entry.storyFile));
      const ns = `stories_${kebabSlot(entry.name).replace(/-/g, "_")}`;
      return `
// ── ${entry.name} (${entry.module}) ────────────────────────────────────────
import * as ${ns} from "${storyImport}";
describe("${entry.name} contract (browser)", () => {
  const meta = ${ns}.default as { component?: unknown; args?: Record<string, unknown> };
  const Default = (${ns} as { Default?: { args?: Record<string, unknown> } }).Default;
  // eslint-disable-next-line @typescript-eslint/no-explicit-any -- probe target; see file header
  const Component = meta.component as any;
  const args = { ...(meta.args ?? {}), ...(Default?.args ?? {}) };

  for (const theme of BUILT_IN_THEMES) {
    for (const width of WIDTHS) {
      describe(\`theme=\${theme} width=\${width}\`, () => {
        async function mount() {
          document.documentElement.setAttribute("data-theme", theme);
          await page.viewport(width, 900);
          return mountReact(<Component {...args} />);
        }

        contractIt("${entry.storyId}", theme, width, "axe", "has no axe violations", async () => {
          const { container, unmount } = await mount();
          try {
            const results = await axe.run(container, { runOnly: ["wcag2a", "wcag2aa"] });
            expect(results.violations.map((v) => v.id)).toEqual([]);
          } finally {
            unmount();
          }
        });

        contractIt(
          "${entry.storyId}",
          theme,
          width,
          "overflow",
          "does not overflow horizontally",
          async () => {
            const { unmount } = await mount();
            try {
              expect(document.documentElement.scrollWidth).toBeLessThanOrEqual(window.innerWidth);
            } finally {
              unmount();
            }
          },
        );
      });
    }
  }
});
`;
    })
    .join("\n");

  const body = `${GENERATED_HEADER}/**
 * Browser contract probes (axe + horizontal-overflow) for every ${pkgShortName}
 * component with a \`Default\` story, swept over every built-in theme and the
 * phone/tablet/desktop widths. See scripts/gen-contract-tests.mjs.
 */
import { describe, it, expect, afterEach } from "vitest";
import { page } from "@vitest/browser/context";
import { createRoot, type Root } from "react-dom/client";
import { act, type ReactNode } from "react";
import axe from "axe-core";
import { BUILT_IN_THEMES } from "@elabs-ai/components-tokens";
import knownFailuresJson from "${knownFailuresImport}";

const KNOWN_FAILURES: Record<string, string> = knownFailuresJson;
const WIDTHS = ${JSON.stringify(WIDTHS)};

function mountReact(node: ReactNode) {
  const container = document.createElement("div");
  document.body.appendChild(container);
  const root: Root = createRoot(container);
  act(() => {
    root.render(node);
  });
  return {
    container,
    unmount() {
      act(() => {
        root.unmount();
      });
      container.remove();
    },
  };
}

afterEach(() => {
  document.documentElement.removeAttribute("data-theme");
});

/** Wrap a known, tracked failure in \`it.fails\` so fixing it forces the key's removal. */
function contractIt(
  storyId: string,
  theme: string,
  width: number,
  assertion: string,
  name: string,
  fn: () => void | Promise<void>,
) {
  const key = \`\${storyId}|\${theme}|\${width}|\${assertion}\`;
  const reason = KNOWN_FAILURES[key];
  if (reason) return it.fails(\`\${name} (known failure: \${reason})\`, fn);
  return it(name, fn);
}
${blocks}`;
  return { outFile, body };
}

// ── write / check ────────────────────────────────────────────────────────

function writeIfChanged(outFile, body, checkOnly, changed) {
  const existing = existsSync(outFile) ? readFileSync(outFile, "utf8") : null;
  if (existing === body) return;
  changed.push(relative(REPO_ROOT, outFile));
  if (!checkOnly) {
    mkdirSync(dirname(outFile), { recursive: true });
    writeFileSync(outFile, body);
  }
}

/** Remove stale generated files this run no longer produces. */
function pruneStale(dir, keepFiles, changed, checkOnly) {
  if (!existsSync(dir)) return;
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (!name.endsWith(".contract.test.tsx")) continue;
    if (keepFiles.has(p)) continue;
    changed.push(relative(REPO_ROOT, p) + " (stale — would remove)");
    if (!checkOnly) rmSync(p);
  }
}

function main(argv) {
  const args = argv.slice(2);
  const checkOnly = args.includes("--check");
  const suiteArg = args.includes("--suite") ? args[args.indexOf("--suite") + 1] : "all";
  const packageFilters = args
    .map((a, i) => (a === "--package" ? args[i + 1] : null))
    .filter(Boolean);

  const manifest = JSON.parse(readFileSync(MANIFEST_PATH, "utf8"));
  const { covered, skipped } = discoverCoverage(manifest);

  const filtered = packageFilters.length
    ? covered.filter((e) => packageFilters.includes(basename(e.pkgDir)))
    : covered;

  const changed = [];
  const keepByDir = new Map();

  if (suiteArg === "all" || suiteArg === "jsdom") {
    for (const entry of filtered) {
      const { outFile, body } = renderJsdomTest(entry);
      writeIfChanged(outFile, body, checkOnly, changed);
      const dir = dirname(outFile);
      if (!keepByDir.has(dir)) keepByDir.set(dir, new Set());
      keepByDir.get(dir).add(outFile);
    }
    for (const [dir, keep] of keepByDir) pruneStale(dir, keep, changed, checkOnly);
  }

  if (suiteArg === "all" || suiteArg === "browser") {
    const byPkg = new Map();
    for (const entry of filtered) {
      const short = basename(entry.pkgDir);
      if (!byPkg.has(short)) byPkg.set(short, []);
      byPkg.get(short).push(entry);
    }
    const keep = new Set();
    for (const [short, entries] of byPkg) {
      const { outFile, body } = renderBrowserTest(short, entries);
      writeIfChanged(outFile, body, checkOnly, changed);
      keep.add(outFile);
    }
    pruneStale(BROWSER_CONTRACT_DIR, keep, changed, checkOnly);
  }

  const skipCounts = {};
  for (const s of skipped) skipCounts[s.reason] = (skipCounts[s.reason] ?? 0) + 1;

  console.log(
    `contract-tests: ${covered.length} component(s) covered, ${skipped.length} skipped ` +
      `(${filtered.length} in scope for this run).`,
  );
  for (const [reason, n] of Object.entries(skipCounts)) console.log(`  skip: ${n} — ${reason}`);

  if (checkOnly) {
    if (changed.length) {
      console.error(`✖ contract-tests --check: ${changed.length} file(s) out of date:`);
      for (const f of changed) console.error(`  ${f}`);
      process.exit(1);
    }
    console.log("✔ contract-tests: generated output is up to date.");
    return;
  }

  console.log(`✔ contract-tests: wrote/updated ${changed.length} file(s).`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main(process.argv);
}
