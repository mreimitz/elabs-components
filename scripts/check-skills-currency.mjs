#!/usr/bin/env node
/**
 * check-skills-currency.mjs — playbook/skill/plugin prose currency gate (#29).
 *
 * check-docs-accuracy.mjs (`pnpm docs:check`) already guards the "authoritative"
 * doc set — README.md, AGENTS.md, CONTRIBUTING.md, PROJECT.md, `docs/**.md`,
 * `.claude/rules/**.md`, `.github/**` — for a stale theme-count claim. That walk
 * is `.md`-only and does not touch `docs/**`'s NON-markdown files, `skills/**`, or
 * the plugin manifests. That gap is exactly where #29's confirmed defect lived:
 * `docs/playbooks/templates/{dashboard,data-app,flow-workspace,settings,
 * screen-states}.tsx` and `docs/playbooks/templates/index.json` (GENERATED by
 * `pnpm gen:templates`, fixed at the source stories, not here) told a coding
 * agent to "verify across all three themes" when only TWO reference themes ship.
 * `scripts/build-agent-kit.mjs` copies `docs/playbooks/` verbatim into the
 * release zip, and that zip's own sanitizer scans `*.md` only — so this class of
 * drift reaches every consumer of the agent kit undetected.
 *
 * This gate closes that gap by scanning the files check-docs-accuracy.mjs does
 * NOT: every file under `docs/playbooks/`, every skill's `SKILL.md`, and the
 * plugin manifests (`.claude-plugin/plugin.json`, `.claude-plugin/marketplace.json`).
 * The facts it checks are sourced from `brand-ui.manifest.json` — the generated
 * ground truth (`pnpm manifest`, freshness-gated by `pnpm manifest:check`):
 *
 *   1. THEME COUNT — no prose in scope may claim a theme count (word form "all
 *      three themes" or numeric "3 themes") that disagrees with
 *      `manifest.themes.length`.
 *   2. PACKAGE-NAME SCOPE — every `@<scope>/components-<slug>` mention must use
 *      the CURRENT scope (`@elabs-ai`, matching `manifest.packages`' keys) — this
 *      is the "old `@brand/*` scope" drift class the original #29 evidence named
 *      — and, when the scope is current, `<slug>` must be a real package: either
 *      one of `manifest.packages`' component packages, or one of the small set of
 *      shipped INFRA packages the component manifest deliberately does not track
 *      (cli/docs/eslint-config/typescript-config — see INFRA_PACKAGE_SUFFIXES).
 *
 * Run via `pnpm skills:currency:check`; self-tested via
 * `pnpm skills:currency:check:test` (plants an in-memory stale fixture and
 * asserts the gate FAILS), mirroring scripts/check-agent-names.mjs.
 *
 * Flags:
 *   --warn   never exit non-zero (dev-hook mode); still prints findings.
 *
 * Dependency-free; locates the repo root relative to this file (cwd-independent).
 */
import { readdirSync, readFileSync, existsSync, statSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join, relative } from "node:path";
import { findThemeCountViolations } from "./lib/theme-count-prose.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = dirname(HERE); // scripts/ -> repo root

const WARN = process.argv.includes("--warn");

// ---------------------------------------------------------------------------
// Facts (sourced from brand-ui.manifest.json)
// ---------------------------------------------------------------------------

/** Shipped package names the "components" manifest deliberately does not track —
 * infra/tooling packages, not distributable component packages. A prose mention
 * of `@elabs-ai/components-<one of these>` is legitimate, not a phantom package.
 * Keep this list tight (mirrors PROSE_IGNORE in check-docs-accuracy.mjs) — add a
 * suffix here only when a REAL, currently-shipping package needs it. */
export const INFRA_PACKAGE_SUFFIXES = new Set([
  "cli",
  "docs",
  "eslint-config",
  "typescript-config",
]);

/** The current package scope. A `@<scope>/components-<slug>` mention with any
 * other scope is the "old `@brand/*` scope" drift class #29's original evidence
 * named. */
export const CURRENT_SCOPE = "elabs-ai";

/**
 * Package-name-scope violations in `text`. `manifestPackageNames` is the Set of
 * full package names from `brand-ui.manifest.json`'s `packages` keys (e.g.
 * "@elabs-ai/components-ui"). Pure — exported for the self-test.
 */
export function findPackageScopeViolations(text, manifestPackageNames) {
  const violations = [];
  const re = /@([a-z0-9][a-z0-9-]*)\/components-([a-z0-9-]+)\b/gi;
  text.split("\n").forEach((line, i) => {
    for (const m of line.matchAll(re)) {
      const scope = m[1].toLowerCase();
      const slug = m[2].toLowerCase();
      if (scope !== CURRENT_SCOPE) {
        violations.push({
          line: i + 1,
          match: m[0],
          reason: `scope "@${scope}" is not the current package scope (@${CURRENT_SCOPE})`,
        });
        continue;
      }
      const full = `@${CURRENT_SCOPE}/components-${slug}`;
      if (!manifestPackageNames.has(full) && !INFRA_PACKAGE_SUFFIXES.has(slug)) {
        violations.push({
          line: i + 1,
          match: m[0],
          reason: `"${full}" is not a real package (not in brand-ui.manifest.json's packages and not a known infra package)`,
        });
      }
    }
  });
  return violations;
}

// ---------------------------------------------------------------------------
// File discovery — the scope check-docs-accuracy.mjs's `.md`-only walk misses
// ---------------------------------------------------------------------------

function walkAll(dir, acc) {
  let ents = [];
  try {
    ents = readdirSync(dir, { withFileTypes: true });
  } catch {
    return acc;
  }
  for (const e of ents) {
    if (e.name === "node_modules") continue;
    const p = join(dir, e.name);
    if (e.isDirectory()) walkAll(p, acc);
    else acc.push(p);
  }
  return acc;
}

const existingFiles = (paths) => paths.filter((f) => existsSync(f) && statSync(f).isFile());

/** Every file this gate scans, repo-root relative paths returned as absolute. */
export function currencyProseFiles(root = REPO_ROOT) {
  const files = [
    ...walkAll(join(root, "docs", "playbooks"), []),
    ...existingFiles(
      readdirSync(join(root, "skills"), { withFileTypes: true })
        .filter((e) => e.isDirectory())
        .map((e) => join(root, "skills", e.name, "SKILL.md")),
    ),
    ...existingFiles([
      join(root, ".claude-plugin", "plugin.json"),
      join(root, ".claude-plugin", "marketplace.json"),
    ]),
  ];
  return files.sort();
}

/** The manifest facts this gate checks prose against. */
export function manifestFacts(root = REPO_ROOT) {
  const mPath = join(root, "brand-ui.manifest.json");
  if (!existsSync(mPath)) return null;
  const manifest = JSON.parse(readFileSync(mPath, "utf8"));
  return {
    themeCount: Array.isArray(manifest.themes) ? manifest.themes.length : null,
    packageNames: new Set(Object.keys(manifest.packages ?? {})),
  };
}

/**
 * Run both checks over `{ file, text }[]` and return `{ themeViolations,
 * scopeViolations }` (repo-relative-path-prefixed strings), given `facts` from
 * manifestFacts(). Exported so the self-test can drive it with in-memory
 * fixtures, mirroring check-agent-names.mjs's checkAgents().
 */
export function checkCurrency(entries, facts) {
  const themeViolations = [];
  const scopeViolations = [];
  for (const { file, text } of entries) {
    for (const v of findThemeCountViolations(text, facts.themeCount)) {
      themeViolations.push(`${file}:${v.line}: claims "${v.match}"`);
    }
    for (const v of findPackageScopeViolations(text, facts.packageNames)) {
      scopeViolations.push(`${file}:${v.line}: "${v.match}" — ${v.reason}`);
    }
  }
  return { themeViolations, scopeViolations };
}

// Only run the gate when executed directly (not when imported by the self-test).
const invokedDirectly = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (invokedDirectly) {
  const facts = manifestFacts();
  if (!facts) {
    console.error(
      "✖ skills-currency: brand-ui.manifest.json not found — run `pnpm manifest` first.",
    );
    process.exit(WARN ? 0 : 1);
  }
  const files = currencyProseFiles();
  const entries = files.map((f) => ({
    file: relative(REPO_ROOT, f),
    text: readFileSync(f, "utf8"),
  }));
  const { themeViolations, scopeViolations } = checkCurrency(entries, facts);

  let failed = false;
  if (themeViolations.length) {
    failed = true;
    console.error(
      `✖ stale theme count in playbook/skill/plugin prose — brand-ui.manifest.json ships ` +
        `${facts.themeCount} theme(s) (${themeViolations.length} violation(s)):`,
    );
    for (const v of themeViolations) console.error("  - " + v);
    console.error(
      `  Fix: say "every theme" (or reference the manifest) instead of a hardcoded count —\n` +
        "  a fixed number goes stale the next time a theme is added or removed. If the source\n" +
        "  is a GENERATED file under docs/playbooks/templates/, fix the story under packages/*/src/\n" +
        "  and run `pnpm gen:templates`, not the generated file.",
    );
  }
  if (scopeViolations.length) {
    failed = true;
    console.error(
      `\n✖ stale/unknown package-name scope in playbook/skill/plugin prose (${scopeViolations.length}):`,
    );
    for (const v of scopeViolations) console.error("  - " + v);
    console.error(
      `  Fix: use the current scope (@${CURRENT_SCOPE}) and a real package name (see\n` +
        "  brand-ui.manifest.json's `packages` keys, or add a genuinely new infra package's\n" +
        "  suffix to INFRA_PACKAGE_SUFFIXES in this script).",
    );
  }
  if (failed) process.exit(WARN ? 0 : 1);
  console.log(
    `✔ skills-currency: theme count + package-name scope consistent with brand-ui.manifest.json ` +
      `(${files.length} playbook/skill/plugin files scanned).`,
  );
}
