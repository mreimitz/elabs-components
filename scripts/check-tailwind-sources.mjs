#!/usr/bin/env node
/**
 * check-tailwind-sources.mjs — Tailwind `@source` coverage gate (#348).
 *
 * Tailwind v4 does not auto-scan workspace packages resolved through
 * `node_modules` — every app CSS file that wants a package's classes compiled
 * must name it with an explicit `@source "…";` directive
 * (`.claude/rules/styling-and-tokens.md` § "Tailwind content scanning"). That
 * convention was prose-only and unchecked: `packages/process` shipped with no
 * `@source` line in `apps/docs/.storybook/preview.css`, so the three Tailwind
 * utilities unique to that package (`h-[36rem]`, `opacity-35`, `inset-x-3`)
 * were never scanned as candidates and produced no CSS rule at all — the
 * process map's canvas measured zero height and its ghosting (the wave's
 * central design rule) was silently half-applied. Every visual/theme-safety
 * observation collected against that surface was collected against an empty
 * canvas, and no gate anywhere could see it (issue #348).
 *
 * ## What this gate asserts
 *
 * For every CSS file under `apps/**` or `fixtures/**` that declares at least
 * one `@source` directive, every workspace `packages/<name>` that ships
 * non-test, non-story `.tsx` source must be named by at least one `@source`
 * pattern that RESOLVES to it — never a string match. Two shapes are
 * supported, because the two files that exist today use different ones:
 *
 *   - SRC shape (`apps/docs/.storybook/preview.css`):
 *     `@source "../../../packages/<name>/src/**\/*.{ts,tsx}";`
 *   - DIST shape (`fixtures/consumer-smoke/src/index.css`, keyed by the
 *     package's own `package.json` `name`, mirroring what a real consumer's
 *     `node_modules` install looks like):
 *     `@source "../node_modules/@elabs-ai/components-<name>/dist";`
 *
 * `@source`'s value is a glob; the part of it that matters for "which
 * directory does this scan" is the prefix BEFORE the first glob-magic
 * character (`*`, `?`, `{`, `}`, `[`, `]`) — mirroring how
 * `@tailwindcss/oxide`'s Scanner resolves a source's base directory. That
 * prefix is resolved relative to the CSS file's OWN directory (never the repo
 * root, and never string-matched) so a pattern pointing at the wrong relative
 * depth is caught rather than waved through as a false "coverage" match — see
 * the self-test's "wrong relative depth" fixture.
 *
 * ## The `packages/tokens` exemption — named and commented, not silent
 *
 * `packages/tokens` ships two non-test `.tsx` files (`theme-provider.tsx`,
 * `decoration-provider.tsx`) but carries NO Tailwind class strings anywhere
 * in its source — its one `className=` occurrence sits inside a doc comment
 * in `decoration-provider.tsx`. A naive ".tsx exists → needs @source" rule
 * would false-fail on it forever. `EXEMPT_PACKAGES` below is the named,
 * commented carve-out issue #348 asks for (the alternative it also offers —
 * scoping by "does non-test source contain a real `className=`/`cn(` class
 * string, outside comments" — was tried and rejected here: distinguishing a
 * real usage from a documentation comment needs a comment-aware scan that is
 * real parsing, not a grep, for one package's sake).
 *
 * ## What this gate deliberately does NOT do
 *
 * - It does not touch `packages/cli/lib/engine.mjs`, which already generates
 *   one `@source` line per installed package from the same array as the
 *   scaffold's dependencies, locked by `packages/cli/test/engine.test.mjs`
 *   (`deps === template imports === @source lines`). That machinery already
 *   solves this problem correctly for every app the CLI scaffolds; this gate
 *   exists because the one CSS file this repo hand-maintains (Storybook's
 *   `preview.css`) is not generated by it.
 * - It does not lint the CONTENTS of a package's Tailwind classes, only that
 *   the package is named by a resolvable `@source` pattern in every CSS file
 *   that has any `@source` directives at all.
 *
 * ## Two known limits — declared, not bugs to fix quietly
 *
 * - **Over-strict base-directory matching.** `matchesSrc()` demands the
 *   resolved `@source` base directory equal `packages/<name>/src` EXACTLY. A
 *   broader but genuinely-covering directive — e.g.
 *   `@source "../../../packages/process/**\/*.{ts,tsx}";`, which
 *   `@tailwindcss/oxide` would happily scan — is REJECTED (verified: exits 1,
 *   prints the canonical suggested line). This is a false positive, not a
 *   hole: it fails loudly rather than silently under-covering, so tightening
 *   `matchesSrc()` to accept it is a nice-to-have, not a fix for a bypass.
 * - **Two blind spots in `tailwindScopedPackages()`'s "does this package need
 *   coverage" heuristic.** It only walks `.tsx` files and explicitly excludes
 *   `*.stories.tsx`. So a package whose Tailwind classes live ONLY in
 *   `*.stories.tsx` (which the `@source` glob's `{ts,tsx}` DOES compile) or
 *   ONLY in `.ts` files would be judged out-of-scope and skipped with no
 *   violation raised — the exact class of silence #348 was. No package in
 *   this repo is in that position today (every in-scope package has non-test,
 *   non-story `.tsx` source), but that is a fact about today's tree, not a
 *   property this gate enforces.
 *
 * Run via `pnpm tailwind-sources:check`; self-tested via
 * `pnpm tailwind-sources:check:test` (plants bad fixtures and asserts the
 * gate FAILS — a gate that can silently stop firing is worse than none,
 * `.claude/rules/quality-gates.md` § "Enforcement over reminders").
 *
 * Dependency-free; locates the repo root relative to this file (cwd-independent).
 */
import { existsSync, readFileSync, readdirSync, statSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const REPO_ROOT = path.dirname(HERE); // scripts/ -> repo root

/** Directory names never descended into while walking for CSS files or package source. */
const SKIP_DIRS = new Set([
  "node_modules",
  ".git",
  "dist",
  "build",
  "storybook-static",
  ".turbo",
  "coverage",
]);

/**
 * Named, commented exemptions from the "ships non-test .tsx -> needs @source"
 * rule. See the file header for why `tokens` is here. Keyed by the directory
 * name under `packages/`.
 */
export const EXEMPT_PACKAGES = {
  tokens:
    "ships two non-test .tsx files (theme-provider.tsx, decoration-provider.tsx) but " +
    "carries no Tailwind class strings anywhere in its source -- its one `className=` " +
    "occurrence is inside a doc comment in decoration-provider.tsx. See issue #348.",
};

/** Glob-magic characters that mark the end of an `@source` value's literal directory prefix. */
const GLOB_MAGIC = /[*?{}[\]]/;

function walk(dir, onFile) {
  let entries;
  try {
    entries = readdirSync(dir, { withFileTypes: true });
  } catch {
    return;
  }
  for (const entry of entries) {
    if (SKIP_DIRS.has(entry.name)) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, onFile);
    else onFile(full);
  }
}

/**
 * Every workspace package (directory under `packages/`) that ships at least
 * one non-test, non-story `.tsx` file, MINUS `EXEMPT_PACKAGES`. Returns
 * `{ name, srcDir }[]`, sorted. Exported for the self-test.
 */
export function tailwindScopedPackages(root = REPO_ROOT) {
  const packagesDir = path.join(root, "packages");
  if (!existsSync(packagesDir)) return [];
  const names = readdirSync(packagesDir, { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .sort();

  const out = [];
  for (const name of names) {
    if (EXEMPT_PACKAGES[name]) continue;
    const srcDir = path.join(packagesDir, name, "src");
    if (!existsSync(srcDir) || !statSync(srcDir).isDirectory()) continue;

    let hasScopedTsx = false;
    walk(srcDir, (file) => {
      if (hasScopedTsx || !file.endsWith(".tsx")) return;
      if (file.endsWith(".test.tsx") || file.endsWith(".stories.tsx")) return;
      hasScopedTsx = true;
    });
    if (hasScopedTsx) out.push({ name, srcDir });
  }
  return out;
}

/** Every `.css` file under `apps/**` or `fixtures/**` that declares >= 1 `@source` directive. */
export function tailwindSourceCssFiles(root = REPO_ROOT) {
  const files = [];
  for (const top of ["apps", "fixtures"]) {
    const base = path.join(root, top);
    if (!existsSync(base)) continue;
    walk(base, (file) => {
      if (!file.endsWith(".css")) return;
      let text;
      try {
        text = readFileSync(file, "utf8");
      } catch {
        return;
      }
      if (extractSourceValues(text).length > 0) files.push(file);
    });
  }
  return files.sort();
}

/**
 * Strip CSS block comments before scanning for `@source` directives, so a
 * directive mentioned only in a doc comment (e.g. an example in a header) is
 * never mistaken for a real one.
 *
 * Deliberately a small state machine, NOT a naive comment-stripping regex: a
 * `@source` glob's own value can legitimately contain a recursive-segment
 * marker (Tailwind's "any depth of directories" wildcard, written as two
 * asterisks between slashes) — read blindly, that four-character run *inside
 * the quoted string* is indistinguishable from an EMPTY CSS comment (an
 * opener immediately followed by a closer), and a regex-based stripper
 * deletes it, silently truncating every SRC-shaped `@source` value and
 * breaking every match. CSS comments cannot begin inside a string literal, so
 * this tracks quote state and only treats a comment opener as one outside a
 * string.
 */
export function stripCssComments(text) {
  let out = "";
  let i = 0;
  let inString = null; // '"' | "'" | null
  while (i < text.length) {
    const ch = text[i];
    if (inString) {
      out += ch;
      if (ch === "\\" && i + 1 < text.length) {
        out += text[i + 1];
        i += 2;
        continue;
      }
      if (ch === inString) inString = null;
      i++;
      continue;
    }
    if (ch === '"' || ch === "'") {
      inString = ch;
      out += ch;
      i++;
      continue;
    }
    if (ch === "/" && text[i + 1] === "*") {
      const end = text.indexOf("*/", i + 2);
      i = end === -1 ? text.length : end + 2;
      continue;
    }
    out += ch;
    i++;
  }
  return out;
}

/** Every `@source "<value>";` (single or double quotes) in a CSS file's text, comments stripped. */
export function extractSourceValues(cssText) {
  const values = [];
  const re = /@source\s+["']([^"']+)["']\s*;/g;
  const code = stripCssComments(cssText);
  let m;
  while ((m = re.exec(code))) values.push(m[1]);
  return values;
}

/**
 * Resolve an `@source` value's scan-root directory, as an absolute path,
 * relative to the CSS FILE's own directory (never the repo root, never a
 * string match) — mirroring how `@tailwindcss/oxide` resolves a source glob's
 * base directory: everything before the first glob-magic segment.
 */
export function sourceBaseDir(cssFile, rawValue) {
  const segments = rawValue.split("/");
  const baseSegments = [];
  for (const seg of segments) {
    if (GLOB_MAGIC.test(seg)) break;
    baseSegments.push(seg);
  }
  const relPath = baseSegments.join("/") || ".";
  return path.resolve(path.dirname(cssFile), relPath);
}

/** Does a resolved `@source` base dir match `packages/<name>/src` exactly (SRC shape)? */
function matchesSrc(resolvedDir, pkgSrcDir) {
  return resolvedDir === path.resolve(pkgSrcDir);
}

/**
 * Does a resolved `@source` base dir match `node_modules/<packageName>/dist`
 * (DIST shape), keyed by the package's own scoped `package.json` name (e.g.
 * `@elabs-ai/components-process`), read fresh rather than assumed?
 */
function matchesDist(resolvedDir, packageName) {
  const suffix = path.join("node_modules", ...packageName.split("/"), "dist");
  return resolvedDir === suffix || resolvedDir.endsWith(path.sep + suffix);
}

function readPackageName(pkgDirName, root = REPO_ROOT) {
  const manifestPath = path.join(root, "packages", pkgDirName, "package.json");
  try {
    return JSON.parse(readFileSync(manifestPath, "utf8")).name ?? null;
  } catch {
    return null;
  }
}

/** Best-effort, human-facing suggestion line for a missing package in a given CSS file. */
function suggestSourceLine(cssFile, rawValues, pkg, packageName) {
  const distExample = rawValues.find((v) => v.includes("node_modules"));
  if (distExample && packageName) {
    const idx = distExample.indexOf("node_modules");
    const prefix = distExample.slice(0, idx);
    return `@source "${prefix}node_modules/${packageName}/dist";`;
  }
  const rel = path.relative(path.dirname(cssFile), pkg.srcDir).split(path.sep).join("/");
  const relPath = rel.startsWith(".") ? rel : `./${rel}`;
  return `@source "${relPath}/**/*.{ts,tsx}";`;
}

/**
 * Run the coverage check. `cssFiles` is `{ path, text }[]`; `packages` is
 * `tailwindScopedPackages()`'s shape. Returns `{ file, package, suggestion }[]`
 * violations — pure, so the self-test can drive it with in-memory fixtures.
 */
export function checkTailwindSources({ cssFiles, packages, root = REPO_ROOT }) {
  const violations = [];
  for (const { path: cssFile, text } of cssFiles) {
    const rawValues = extractSourceValues(text);
    if (rawValues.length === 0) continue; // not an @source-bearing file
    const resolvedDirs = rawValues.map((v) => sourceBaseDir(cssFile, v));

    for (const pkg of packages) {
      const packageName = readPackageName(pkg.name, root);
      const covered = resolvedDirs.some(
        (dir) => matchesSrc(dir, pkg.srcDir) || (packageName && matchesDist(dir, packageName)),
      );
      if (!covered) {
        violations.push({
          file: path.relative(root, cssFile),
          package: pkg.name,
          suggestion: suggestSourceLine(cssFile, rawValues, pkg, packageName),
        });
      }
    }
  }
  return violations;
}

// ──────────────────────────────── CLI ─────────────────────────────────────────
// `--root <dir>` scans a different tree — used by the self-test's on-disk fixtures.
export function main(argv) {
  const args = argv.slice(2);
  const rootIdx = args.indexOf("--root");
  const root = rootIdx >= 0 ? args[rootIdx + 1] : REPO_ROOT;

  const packages = tailwindScopedPackages(root);
  const cssPaths = tailwindSourceCssFiles(root);
  const cssFiles = cssPaths.map((p) => ({ path: p, text: readFileSync(p, "utf8") }));

  const violations = checkTailwindSources({ cssFiles, packages, root });

  if (violations.length > 0) {
    console.error(
      `\n✖ tailwind-sources: ${violations.length} package/CSS-file gap(s) — a package with ` +
        "Tailwind class strings is not named by a resolvable @source directive:\n",
    );
    for (const v of violations) {
      console.error(`  - packages/${v.package} is missing from ${v.file}`);
      console.error(`      add: ${v.suggestion}`);
    }
    console.error(
      "\n  Tailwind v4 does not auto-scan workspace packages resolved via node_modules -- " +
        "an unlisted package renders UNSTYLED with every gate green (see issue #348 and " +
        '.claude/rules/styling-and-tokens.md § "Tailwind content scanning").\n',
    );
    return 1;
  }

  console.log(
    `✔ tailwind-sources: every package with Tailwind class strings is covered across ` +
      `${cssPaths.length} @source-bearing CSS file(s).`,
  );
  return 0;
}

// Only run the gate when executed directly (not when imported by the self-test).
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  process.exit(main(process.argv));
}
