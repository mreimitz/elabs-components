#!/usr/bin/env node
/**
 * gen-community-themes.mjs — wire the downloadable theme families in `themes/`
 * into the docs Storybook (ADR 0036), so every family is previewable on real
 * components from the Theme / Mode toolbar.
 *
 * Emits, under `apps/docs/.storybook/`:
 *   - `community-themes.generated.css` — one `@import` per family stylesheet
 *     (a family's `<slug>-fonts.css` first, when it ships one)
 *   - `community-themes.generated.ts`  — the families' `ThemeDefinition`s as
 *     plain data (parsed from each `theme.ts`; the docs app never imports the
 *     `themes/` folder's TS, which lives outside any workspace package)
 *
 *   node scripts/gen-community-themes.mjs          # write (part of `pnpm gen`)
 *   node scripts/gen-community-themes.mjs --check  # exit 1 when stale
 *
 * Freshness is also asserted by `pnpm community-themes:check`.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

import {
  COMMUNITY_THEMES_DIR,
  auditFamily,
  formatForPath,
  listFamilies,
  readRootDeclarations,
  readTokenNames,
} from "./lib/community-themes.mjs";
import { REPO_ROOT } from "./lib/theme-sources.mjs";

export const STORYBOOK_DIR = join(REPO_ROOT, "apps", "docs", ".storybook");
export const GENERATED_CSS = join(STORYBOOK_DIR, "community-themes.generated.css");
export const GENERATED_TS = join(STORYBOOK_DIR, "community-themes.generated.ts");

const HEADER =
  "GENERATED by scripts/gen-community-themes.mjs from themes/ — do not edit. Run `pnpm gen`.";

/** Every variant of every family, in folder then light→dark order. */
export function collectVariants(dir = COMMUNITY_THEMES_DIR) {
  const tokenNames = readTokenNames();
  const root = readRootDeclarations();
  return listFamilies(dir).flatMap((slug) => auditFamily(slug, { dir, tokenNames, root }).variants);
}

/**
 * The engine's `dark:` variant matches only `[data-theme="dark"]`. A later
 * `@custom-variant dark` replaces it, so redeclare it to cover every downloaded
 * dark variant too — the same line `themes/README.md` tells consumers to add.
 */
export function renderDarkVariant(variants) {
  const names = [
    "dark",
    ...variants.filter((v) => v.definition?.dark).map((v) => v.definition.value),
  ];
  const selectors = names.flatMap((n) => [`[data-theme="${n}"]`, `[data-theme="${n}"] *`]);
  return `@custom-variant dark (&:where(${selectors.join(", ")}));`;
}

export function renderCss(variants) {
  const rel = (file) => `@import "${relative(STORYBOOK_DIR, file).split("\\").join("/")}";`;
  // A family's `<slug>-fonts.css` (its self-hosted typeface) loads before the scheme
  // files that select it — once per family, not once per variant.
  const fonts = [...new Set(variants.map((v) => v.fonts).filter(Boolean))].map(rel);
  const imports = variants.map((v) => rel(v.file));
  return [`/* ${HEADER} */`, ...fonts, ...imports, renderDarkVariant(variants), ""].join("\n");
}

export function renderTs(variants) {
  const entries = variants
    .filter((v) => v.definition)
    .map(({ definition: d }) => {
      const fields = [
        `value: ${JSON.stringify(d.value)}`,
        `label: ${JSON.stringify(d.label ?? d.value)}`,
        `dark: ${d.dark === true}`,
        `family: ${JSON.stringify(d.family)}`,
        ...(d.familyLabel ? [`familyLabel: ${JSON.stringify(d.familyLabel)}`] : []),
      ];
      return `  { ${fields.join(", ")} },`;
    });
  return `/** ${HEADER} */
import type { ThemeDefinition } from "@elabs-ai/components-tokens";

export const COMMUNITY_THEME_DEFINITIONS: readonly ThemeDefinition[] = [
${entries.join("\n")}
];
`;
}

/** `[path, formatted content]` for every generated file. */
async function expectedOutputs(variants) {
  return [
    [GENERATED_CSS, await formatForPath(GENERATED_CSS, renderCss(variants))],
    [GENERATED_TS, await formatForPath(GENERATED_TS, renderTs(variants))],
  ];
}

/** Stale generated files, as repo-relative paths (empty = fresh). */
export async function staleOutputs(variants = collectVariants()) {
  return (await expectedOutputs(variants))
    .filter(([path, content]) => {
      try {
        return readFileSync(path, "utf8") !== content;
      } catch {
        return true;
      }
    })
    .map(([path]) => relative(REPO_ROOT, path));
}

async function main(argv) {
  const variants = collectVariants();
  if (argv.includes("--check")) {
    const stale = await staleOutputs(variants);
    if (stale.length === 0) return 0;
    console.error(`gen-community-themes: stale ${stale.join(", ")} — run \`pnpm gen\`.`);
    return 1;
  }
  for (const [path, content] of await expectedOutputs(variants)) writeFileSync(path, content);
  console.log(`gen-community-themes: ${variants.length} theme variant(s) → apps/docs/.storybook`);
  return 0;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  process.exitCode = await main(process.argv.slice(2));
}
