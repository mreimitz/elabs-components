/** Terse column constructors, so the model below reads like a schema rather than like JSON. */
const pk = (name = "id"): ModelColumn => ({ name, type: "uuid", keys: ["pk"] });
const fk = (name: string, nullable = false): ModelColumn => ({
  name,
  type: "uuid",
  keys: ["fk"],
  nullable,
});
const col = (name: string, type: string, extra: Partial<ModelColumn> = {}): ModelColumn => ({
  name,
  type,
  ...extra,
});

